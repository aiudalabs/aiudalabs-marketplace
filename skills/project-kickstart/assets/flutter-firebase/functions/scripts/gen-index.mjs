// Writes src/index.ts, the Cloud Functions entry point for {{project_title}}.
// Owner: firebase-dev.
//
// Each function lives in its own file under src/callable/, src/triggers/,
// src/scheduled/ or src/https/ and exports itself by name:
//
//   // src/callable/acceptBooking.ts
//   export const acceptBooking = onCall(...);
//
// The build, typecheck, lint and test scripts run this first, so an issue that
// adds a function touches only its own file and no two issues edit one barrel.
// src/index.ts is generated, ignored by git, and never edited by hand.
// Two files exporting the same name fail the typecheck (TS2308).

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const src = join(dirname(fileURLToPath(import.meta.url)), '..', 'src');
const FOLDERS = ['callable', 'triggers', 'scheduled', 'https'];

const lines = [
  '// Generated by scripts/gen-index.mjs. Do not edit: add a file under',
  `// ${FOLDERS.map((f) => `src/${f}/`).join(', ')} instead.`,
  '',
  "import './init';",
  '',
];
for (const folder of FOLDERS) {
  const dir = join(src, folder);
  if (!existsSync(dir)) continue;
  const files = readdirSync(dir)
    .filter((file) => file.endsWith('.ts') && !file.endsWith('.test.ts') && !file.endsWith('.d.ts'))
    .sort();
  for (const file of files) lines.push(`export * from './${folder}/${file.slice(0, -3)}';`);
}
const content = `${lines.join('\n')}\n`;
const target = join(src, 'index.ts');
if (!existsSync(target) || readFileSync(target, 'utf8') !== content) writeFileSync(target, content);
